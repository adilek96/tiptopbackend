import { definePolicies } from "@medusajs/framework/utils"

/**
 * Права кассы.
 *
 * Ресурс `pos` — наш собственный: политика в Medusa это просто пара строк
 * resource/operation, и заводить свою область прав можно без изменений
 * в ядре.
 *
 * Объявлять их обязательно именно здесь. При каждом старте модуль ролей
 * сверяет таблицу политик с этим каталогом и всё, чего в нём нет, мягко
 * удаляет. Политика, созданная руками через админку или SQL, пережила бы
 * ровно один рестарт, после чего роль кассира потеряла бы права молча.
 *
 * Каталог собирается из всех папок `policies` в проекте — их находит
 * загрузчик ядра при запуске.
 */
export const posPolicies = definePolicies([
  {
    name: "ReadPos",
    resource: "pos",
    operation: "read",
    description: "Поиск товара и остатков на кассе",
  },
  {
    name: "CreatePos",
    resource: "pos",
    operation: "create",
    description: "Проведение продажи на кассе",
  },
])
